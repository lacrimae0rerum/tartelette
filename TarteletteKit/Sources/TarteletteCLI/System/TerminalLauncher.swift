import Foundation
import TarteletteCore

/// Opens commands that need a real terminal (TTY) in Terminal.app, e.g. `tart exec -it vm zsh -l`
/// or `ssh admin@192.168.64.3`.
public enum TerminalLauncher {
  /// Writes a one-shot `.command` script and opens it in Terminal.
  ///
  /// - Parameters:
  ///   - commandLine: A shell command line (quote arguments with `ShellQuoting`).
  ///   - title: The Terminal window title.
  ///   - tartDirectory: The directory of the Tart the app uses, put first on `PATH` so `tart` there
  ///     is that Tart even when it isn't on the user's `PATH` (a copy Tartelette manages).
  public static func open(commandLine: String, title: String, tartDirectory: URL? = nil) throws {
    let script = try makeScript(commandLine: commandLine, title: title, tartDirectory: tartDirectory)
    let open = Process()
    open.executableURL = URL(fileURLWithPath: "/usr/bin/open")
    open.arguments = ["-a", "Terminal", script.path]
    try open.run()
  }

  /// Creates the executable script in a per-user temporary directory and returns its URL.
  static func makeScript(
    commandLine: String, title: String, directory: URL? = nil, tartDirectory: URL? = nil
  ) throws -> URL {
    let folder =
      directory
      ?? FileManager.default.temporaryDirectory.appendingPathComponent("Tartelette Terminal", isDirectory: true)
    try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)

    let safeTitle = title.unicodeScalars
      .map { CharacterSet.alphanumerics.contains($0) ? String($0) : "-" }
      .joined()
      .prefix(40)
    let script = folder.appendingPathComponent("\(safeTitle)-\(UUID().uuidString.prefix(8)).command")

    var lines = [
      "#!/bin/zsh",
      "# Generated by Tartelette. This file deletes itself when it runs.",
      "rm -f -- \"$0\"",
      "export PATH=\"/opt/homebrew/bin:/usr/local/bin:$PATH\"",
    ]
    // The Tart the app uses comes first, even when it isn't on the user's PATH.
    if let tartDirectory {
      lines.append("export PATH=\(ShellQuoting.quote(tartDirectory.path)):\"$PATH\"")
    }
    lines += ["printf '\\e]0;%s\\a' \(ShellQuoting.quote(title))", "clear", "exec \(commandLine)", ""]
    let body = lines.joined(separator: "\n")
    try body.write(to: script, atomically: true, encoding: .utf8)
    try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: script.path)
    return script
  }
}
